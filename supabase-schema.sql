create or replace function public.submit_spot_game_score(
  p_name text,
  p_side text,
  p_elapsed_ms integer,
  p_mistakes integer,
  p_player_token text
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  clean_name text := trim(coalesce(p_name, ''));
  clean_token text := coalesce(p_player_token, '');
  calculated_total integer;
  affected_rows integer;
begin
  if char_length(clean_name) not between 1 and 12 then
    raise exception 'invalid name';
  end if;

  if p_side not in ('신랑', '신부') then
    raise exception 'invalid side';
  end if;

  if p_elapsed_ms is null or p_elapsed_ms not between 3000 and 3600000 then
    raise exception 'invalid elapsed time';
  end if;

  if p_mistakes is null or p_mistakes not between 0 and 999 then
    raise exception 'invalid mistakes';
  end if;

  if char_length(clean_token) not between 12 and 200 then
    raise exception 'invalid player token';
  end if;

  calculated_total := p_elapsed_ms + (p_mistakes * 3000);

  insert into public.spot_game_scores (
    game_key,
    player_token_hash,
    side,
    name,
    elapsed_ms,
    mistakes,
    total_ms
  )
  values (
    'wedding-01',
    encode(digest(clean_token, 'sha256'), 'hex'),
    p_side,
    clean_name,
    p_elapsed_ms,
    p_mistakes,
    calculated_total
  )
  on conflict (game_key, player_token_hash)
  do update set
    side = excluded.side,
    name = excluded.name,
    elapsed_ms = excluded.elapsed_ms,
    mistakes = excluded.mistakes,
    total_ms = excluded.total_ms,
    created_at = now()
  where excluded.total_ms < spot_game_scores.total_ms;

  get diagnostics affected_rows = row_count;
  return affected_rows > 0;
end;
$$;

create or replace function public.list_spot_game_scores()
returns table (
  ranking_position bigint,
  side text,
  name text,
  total_ms integer,
  created_at timestamptz
)
language sql
security definer
set search_path = public, pg_temp
as $$
  select
    row_number() over (order by scores.total_ms, scores.created_at),
    scores.side,
    scores.name,
    scores.total_ms,
    scores.created_at
  from public.spot_game_scores as scores
  where scores.game_key = 'wedding-01'
  order by scores.total_ms, scores.created_at
  limit 10;
$$;

create or replace function public.get_spot_game_team_scores()
returns table (
  side text,
  total_points bigint,
  player_count bigint
)
language sql
security definer
set search_path = public, pg_temp
as $$
  with teams(side) as (
    values ('신랑'::text), ('신부'::text)
  )
  select
    teams.side,
    coalesce(sum(greatest(100, 10000 - (scores.total_ms / 10))), 0)::bigint as total_points,
    count(scores.id)::bigint as player_count
  from teams
  left join public.spot_game_scores as scores
    on scores.side = teams.side
    and scores.game_key = 'wedding-01'
  group by teams.side
  order by teams.side;
$$;

