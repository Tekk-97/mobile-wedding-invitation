    execute format('alter table public.guestbook drop constraint if exists %I', constraint_record.conname);
  end loop;
end $$;

alter table public.guestbook
  add constraint guestbook_name_length check (char_length(name) between 1 and 20),
  add constraint guestbook_attendance_valid check (attendance in ('참석 예정', '불참', '미정')),
  add constraint guestbook_message_length check (char_length(message) between 1 and 300);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  created_at timestamptz not null default now()
);

alter table public.guestbook enable row level security;
alter table public.admin_users enable row level security;

drop policy if exists "Anyone can read guestbook" on public.guestbook;
drop policy if exists "Anyone can write guestbook" on public.guestbook;
drop policy if exists "Admins can update guestbook" on public.guestbook;
drop policy if exists "Admins can delete guestbook" on public.guestbook;
drop policy if exists "Admins can read admin users" on public.admin_users;

create policy "Anyone can read guestbook"
on public.guestbook
for select
to anon, authenticated
using (true);

create policy "Admins can update guestbook"
on public.guestbook
for update
to authenticated
using (
  exists (
    select 1
    from public.admin_users
    where admin_users.user_id = auth.uid()
  )
)
with check (
  exists (
    select 1
    from public.admin_users
    where admin_users.user_id = auth.uid()
  )
  and char_length(name) between 1 and 20
  and attendance in ('참석 예정', '불참', '미정')
  and char_length(message) between 1 and 300
);

create policy "Admins can delete guestbook"
on public.guestbook
for delete
to authenticated
using (
  exists (
    select 1
    from public.admin_users
    where admin_users.user_id = auth.uid()
  )
);

create policy "Admins can read admin users"
on public.admin_users
for select
to authenticated
using (user_id = auth.uid());

create index if not exists guestbook_created_at_idx
on public.guestbook (created_at desc);

create or replace function public.list_guestbook_entries(
  p_owner_token text
)
returns table (
  id bigint,
  name text,
  attendance text,
  message text,
  created_at timestamptz,
  can_edit boolean
)
language sql
security definer
set search_path = public, extensions, pg_temp
as $$
  select
    guestbook.id,
    guestbook.name,
    guestbook.attendance,
    guestbook.message,
    guestbook.created_at,
    guestbook.owner_token_hash = crypt(p_owner_token, guestbook.owner_token_hash) as can_edit
  from public.guestbook
  order by guestbook.created_at desc
  limit 50;
$$;

create or replace function public.create_guestbook_entry(
  p_name text,
  p_attendance text,
  p_message text,
  p_owner_token text
)
returns bigint
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  new_id bigint;
begin
  if char_length(p_name) not between 1 and 20 then
    raise exception 'invalid name';
  end if;

  if p_attendance not in ('참석 예정', '불참', '미정') then
    raise exception 'invalid attendance';
  end if;

  if char_length(p_message) not between 1 and 300 then
    raise exception 'invalid message';
  end if;

  if char_length(p_owner_token) not between 12 and 200 then
    raise exception 'invalid owner token';
  end if;

  insert into public.guestbook (name, attendance, message, owner_token_hash)
  values (p_name, p_attendance, p_message, crypt(p_owner_token, gen_salt('bf')))
  returning id into new_id;

  return new_id;
end;
$$;

create or replace function public.update_guestbook_entry(
  p_id bigint,
  p_name text,
  p_attendance text,
  p_message text,
  p_owner_token text
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  if char_length(p_name) not between 1 and 20 then
    return false;
  end if;

  if p_attendance not in ('참석 예정', '불참', '미정') then
    return false;
  end if;

  if char_length(p_message) not between 1 and 300 then
    return false;
  end if;

  update public.guestbook
  set
    name = p_name,
    attendance = p_attendance,
    message = p_message
  where id = p_id
    and owner_token_hash = crypt(p_owner_token, owner_token_hash);

  return found;
end;
$$;

create or replace function public.delete_guestbook_entry(
  p_id bigint,
  p_owner_token text
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  delete from public.guestbook
  where id = p_id
    and owner_token_hash = crypt(p_owner_token, owner_token_hash);

  return found;
end;
$$;

create or replace function public.is_guestbook_admin()
returns boolean
language sql
security definer
set search_path = public, extensions, pg_temp
as $$
  select exists (
    select 1
    from public.admin_users
    where admin_users.user_id = auth.uid()
  );
$$;

