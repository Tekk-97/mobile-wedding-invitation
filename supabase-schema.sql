-- 참석 의사 응답은 방명록과 분리해 저장합니다.
create table if not exists public.rsvp_responses (
  id bigint generated by default as identity primary key,
  side text not null,
  attendance text not null,
  name text not null,
  phone_last4 text not null,
  party_size integer not null default 1,
  note text not null default '',
  created_at timestamptz not null default now(),
  constraint rsvp_side_valid check (side in ('신랑', '신부')),
  constraint rsvp_attendance_valid check (attendance in ('참석', '불참')),
  constraint rsvp_name_length check (char_length(name) between 1 and 20),
  constraint rsvp_phone_last4_valid check (phone_last4 ~ '^[0-9]{4}$'),
  constraint rsvp_party_size_valid check (party_size between 1 and 5),
  constraint rsvp_note_length check (char_length(note) <= 100)
);

alter table public.rsvp_responses enable row level security;

drop policy if exists "Admins can read RSVP responses" on public.rsvp_responses;
drop policy if exists "Admins can delete RSVP responses" on public.rsvp_responses;

create policy "Admins can read RSVP responses"
on public.rsvp_responses
for select
to authenticated
using (public.is_guestbook_admin());

create policy "Admins can delete RSVP responses"
on public.rsvp_responses
for delete
to authenticated
using (public.is_guestbook_admin());

create index if not exists rsvp_responses_created_at_idx
on public.rsvp_responses (created_at desc);

create or replace function public.submit_rsvp_response(
  p_side text,
  p_attendance text,
  p_name text,
  p_phone_last4 text,
  p_party_size integer,
  p_note text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  new_id bigint;
  clean_name text := trim(coalesce(p_name, ''));
  clean_note text := trim(coalesce(p_note, ''));
begin
  if p_side not in ('신랑', '신부') then
    raise exception 'invalid side';
  end if;

  if p_attendance not in ('참석', '불참') then
    raise exception 'invalid attendance';
  end if;

  if char_length(clean_name) not between 1 and 20 then
    raise exception 'invalid name';
  end if;

  if p_phone_last4 is null or p_phone_last4 !~ '^[0-9]{4}$' then
    raise exception 'invalid phone';
  end if;

  if p_party_size is null or p_party_size not between 1 and 5 then
    raise exception 'invalid party size';
  end if;

  if char_length(clean_note) > 100 then
    raise exception 'invalid note';
  end if;

  insert into public.rsvp_responses (side, attendance, name, phone_last4, party_size, note)
  values (p_side, p_attendance, clean_name, p_phone_last4, p_party_size, clean_note)
  returning id into new_id;

  return new_id;
end;
$$;

create or replace function public.admin_delete_rsvp_response(p_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.is_guestbook_admin() then
    return false;
  end if;

  delete from public.rsvp_responses where id = p_id;
  return found;
end;
$$;

grant execute on function public.submit_rsvp_response(text, text, text, text, integer, text) to anon, authenticated;
grant execute on function public.admin_delete_rsvp_response(bigint) to authenticated;

