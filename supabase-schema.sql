create table if not exists public.rsvp_responses (
  id bigint generated by default as identity primary key,
  side text not null,
  attendance text not null,
  name text not null,
  phone_last4 text not null,
  party_size integer not null default 1,
  note text not null default '',
  created_at timestamptz not null default now(),
  constraint rsvp_side_valid check (side in ('신랑', '신부')),
  constraint rsvp_attendance_valid check (attendance in ('참석', '불참')),
  constraint rsvp_name_length check (char_length(name) between 1 and 20),
  constraint rsvp_phone_last4_valid check (phone_last4 ~ '^[0-9]{4}$'),
  constraint rsvp_party_size_valid check (party_size between 1 and 5),
  constraint rsvp_note_length check (char_length(note) <= 100)
);

alter table public.rsvp_responses enable row level security;

