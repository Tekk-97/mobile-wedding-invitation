create table if not exists public.guestbook (
  id bigint generated by default as identity primary key,
  name text not null,
  attendance text not null default '참석 예정',
  message text not null,
  edit_code_hash text,
  owner_token_hash text,
  created_at timestamptz not null default now()
);

create extension if not exists pgcrypto;

drop function if exists public.create_guestbook_entry(text, text, text, text);
drop function if exists public.update_guestbook_entry(bigint, text, text, text, text);
drop function if exists public.delete_guestbook_entry(bigint, text);
drop function if exists public.list_guestbook_entries(text);
drop function if exists public.admin_update_guestbook_entry(bigint, text, text, text);
drop function if exists public.admin_delete_guestbook_entry(bigint);

alter table public.guestbook
  add column if not exists edit_code_hash text;

alter table public.guestbook
  add column if not exists owner_token_hash text;

update public.guestbook
set edit_code_hash = crypt(gen_random_uuid()::text, gen_salt('bf'))
where edit_code_hash is null;

alter table public.guestbook
  alter column edit_code_hash drop not null;

update public.guestbook
set owner_token_hash = crypt(gen_random_uuid()::text, gen_salt('bf'))
where owner_token_hash is null;

alter table public.guestbook
  alter column owner_token_hash set not null;

do $$
declare
