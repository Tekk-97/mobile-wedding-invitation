create or replace function public.submit_rsvp_response(
  p_side text,
  p_attendance text,
  p_name text,
  p_phone_last4 text,
  p_party_size integer,
  p_note text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  new_id bigint;
  clean_name text := trim(coalesce(p_name, ''));
  clean_note text := trim(coalesce(p_note, ''));
begin
  if p_side not in ('신랑', '신부') then
    raise exception 'invalid side';
  end if;

  if p_attendance not in ('참석', '불참') then
    raise exception 'invalid attendance';
  end if;

  if char_length(clean_name) not between 1 and 20 then
    raise exception 'invalid name';
  end if;

  if p_phone_last4 is null or p_phone_last4 !~ '^[0-9]{4}$' then
    raise exception 'invalid phone';
  end if;

  if p_party_size is null or p_party_size not between 1 and 5 then
    raise exception 'invalid party size';
  end if;

  if char_length(clean_note) > 100 then
    raise exception 'invalid note';
  end if;

  insert into public.rsvp_responses (side, attendance, name, phone_last4, party_size, note)
  values (p_side, p_attendance, clean_name, p_phone_last4, p_party_size, clean_note)
  returning id into new_id;

  return new_id;
end;
$$;

create or replace function public.admin_delete_rsvp_response(p_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.is_guestbook_admin() then
    return false;
  end if;

  delete from public.rsvp_responses where id = p_id;
  return found;
end;
$$;

grant execute on function public.submit_rsvp_response(text, text, text, text, integer, text) to anon, authenticated;
grant execute on function public.admin_delete_rsvp_response(bigint) to authenticated;

